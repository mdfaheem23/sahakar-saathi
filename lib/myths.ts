  if (!q) return null;

  let best: MythEntry | null = null;
  let bestScore = 0;

  for (const myth of MYTHS) {
    let score = 0;
    for (const kw of myth.keywords[lang] ?? []) {
      if (q.includes(kw.toLowerCase())) score += 3;
    }
    for (const kw of myth.keywords.en) {
      if (q.includes(kw.toLowerCase())) score += 2;
    }
    if (score > bestScore) {
      bestScore = score;
      best = myth;
    }
  }

  return bestScore > 0 ? best : null;
