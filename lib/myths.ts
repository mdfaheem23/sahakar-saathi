// "Is this true?" — misinformation & rent-seeking verifier
//
// The dominant failure mode in rural scheme delivery is not that information
// is unavailable — it is that an intermediary supplies WRONG information for
// profit ("pay me ₹2,000 and I'll file your claim"). A farmer cannot fact-check
// a middleman standing in front of them.
//
// So this flips the chatbot into a verification tool: the farmer repeats what
// they were told, and the assistant rules on it against the source documents.
// ---------------------------------------------------------------------------

